"""Generate the Lean model of exported networks.

For each network under `networks/` (or the ones named), writes `networks/<name>/Model.lean`,
whose `batfish_snapshot` command reads the snapshot that `export.py` exported next to it, in
`networks/<name>/export/`, and defines the network's semantics. Build them, and any `Properties.lean` next to them,
with `lake build networks`.
"""

import argparse
import subprocess
from pathlib import Path

from common import EXPORT, NETWORKS, ROOT

SIM = ROOT / ".lake" / "build" / "bin" / "lean-batfish-sim"

TEMPLATE = '''import LeanBatfish

/-!
# The `{network}` network

Generated by `tools/model.py` from the snapshot in this folder, as Batfish exported it to
`{export}/`. Defines `Networks.{name}.snapshot`, `Networks.{name}.network` and
`Networks.{name}.converged` (see `LeanBatfish.Model.Command`).
-/

batfish_snapshot Networks.{name} from "{export}"
'''


def lean_name(network: str) -> str:
    return "".join(part.capitalize() for part in network.replace("_", "-").split("-"))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("networks", nargs="*", help="network names (default: all exported ones)")
    args = ap.parse_args()

    names = args.networks or sorted(p.name for p in NETWORKS.iterdir() if p.is_dir())
    for network in names:
        data = NETWORKS / network / EXPORT
        if not (data / "viModel.json").exists():
            print(f"skipping {network}: not exported (run tools/export.py networks/{network})")
            continue
        decoded = subprocess.run([SIM, "decode", str(data / "viModel.json")],
                                 capture_output=True, text=True)
        if decoded.returncode != 0:
            print(f"skipping {network}: outside the modeled subset ({decoded.stdout.strip()[:120]})")
            continue
        name = lean_name(network)
        out = NETWORKS / network / "Model.lean"
        out.write_text(TEMPLATE.format(network=network, name=name, export=EXPORT))
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
